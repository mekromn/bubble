/**
 * Physical, same-process renderer A/B recorder.
 *
 * Measurement is deliberately dormant unless the user starts a run. Both renderer arms keep
 * Build-140 UNBUFFERED_140 page input. Blocks are counterbalanced by pair and begin only on a fresh
 * physical ACTION_DOWN after the selected real floating renderer is live and has Android window
 * focus. No synthetic page input is generated by this class.
 *
 * Scope warnings are intentional: Choreographer cadence is Bubble's app/UI scheduler cadence, not
 * Gecko/SurfaceFlinger presentation FPS; input->Choreographer is not touch-to-photon; process CPU,
 * PSS and allocation counters describe Bubble's app process, not every Gecko/system process.
 */
internal object RendererBenchmark {
    private const val TARGET_BLOCK_NS = 8_000_000_000L
    private const val HARD_BLOCK_NS = 25_000_000_000L
    private const val BETWEEN_BLOCK_MS = 1900L
    private const val READY_SETTLE_MS = 450L
    private const val READY_TIMEOUT_MS = 20_000L
    private const val HIST_BINS = 512

    private val main = Handler(Looper.getMainLooper())
    private var run: RunState? = null
    private var pending: PendingBlock? = null
    private var active: Recorder? = null
    private var frameLoopPosted = false

    private val frameCallback = Choreographer.FrameCallback { frameTimeNanos ->
        frameLoopPosted = false
        val recorder = active
        if (recorder != null && recorder.startedNanos != 0L) recorder.onFrame(frameTimeNanos)
        if (run != null) ensureFrameLoop()
    }

