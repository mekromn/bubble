    private class Histogram(private val widthNs: Long) {
        private val bins = LongArray(HIST_BINS)
        var count = 0L
            private set
        fun add(valueNs: Long) {
            val value = valueNs.coerceAtLeast(0L)
            val index = min((value / widthNs).toInt(), HIST_BINS - 1)
            bins[index]++
            count++
        }
        fun percentile(q: Double): Double {
            if (count == 0L) return Double.NaN
            val target = max(1L, ceil(count * q.coerceIn(0.0, 1.0)).toLong())
            var total = 0L
            for (i in bins.indices) {
                total += bins[i]
                if (total >= target) return (i + 0.5) * widthNs / 1_000_000.0
            }
            return (HIST_BINS - 0.5) * widthNs / 1_000_000.0
        }
    }

