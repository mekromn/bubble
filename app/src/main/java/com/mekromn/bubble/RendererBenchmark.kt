    fun status(context: Context): Status {
        val state = run
        val p = pending
        val a = active
        val latest = context.getSharedPreferences("renderer-benchmark", Context.MODE_PRIVATE)
            .getString("latest-summary", "No completed measured run yet.").orEmpty()
        return when {
            state == null -> Status(false, 0, 0, "idle", latest)
            a != null -> Status(true, a.index + 1, state.order.size, "measuring ${methodLabel(a.transport)}", latest)
            p != null -> Status(true, p.index + 1, state.order.size, if (p.ready) "ready for next physical gesture" else "preparing renderer", latest)
            else -> Status(true, state.results.size + 1, state.order.size, "switching / analyzing", latest)
        }
    }

    fun start(context: Context, pairs: Int): Boolean {
        check(Looper.myLooper() == Looper.getMainLooper())
        if (run != null) return false
        val window = BubbleService.active?.window
        val session = Workspace.peek()?.selected?.session
        if (window == null || window.mode != FloatingMode.CHAT || session == null || !session.isOpen) {
            Toast.makeText(context, "Open a live floating chat/page before starting the renderer benchmark.", Toast.LENGTH_LONG).show()
            return false
        }
        val count = pairs.coerceIn(2, 12)
        val seed = SystemClock.elapsedRealtimeNanos() xor BuildFingerprint.seed()
        val order = ArrayList<RendererArena.Transport>(count * 2)
        val firstDirect = (seed and 1L) == 0L
        repeat(count) { pair ->
            val directFirst = if (pair % 2 == 0) firstDirect else !firstDirect
            if (directFirst) {
                order += RendererArena.Transport.DIRECT_GECKO_SURFACE
                order += RendererArena.Transport.RELAY_LATEST_BP
            } else {
                order += RendererArena.Transport.RELAY_LATEST_BP
                order += RendererArena.Transport.DIRECT_GECKO_SURFACE
            }
        }
        val app = context.applicationContext
        run = RunState(app, count, seed, order)
        PageTouchDispatch.arm = PageTouchDispatch.Arm.UNBUFFERED_140
        ensureFrameLoop()
        scheduleBlock(0)
        return true
    }

    fun cancel(message: String = "Renderer benchmark canceled.") {
        val state = run ?: return
        active?.targetFinish?.let(main::removeCallbacks)
        active?.hardFinish?.let(main::removeCallbacks)
        active = null
        pending = null
        run = null
        PageTouchDispatch.arm = PageTouchDispatch.Arm.UNBUFFERED_140
        RendererArena.transport = RendererArena.Transport.DIRECT_GECKO_SURFACE
        BubbleService.active?.window?.setRendererTransportForArena(RendererArena.Transport.DIRECT_GECKO_SURFACE)
        Toast.makeText(state.app, message, Toast.LENGTH_LONG).show()
    }

    /** Returns a non-zero token only for events inside a measured real floating-page block. */
    fun beforePage(view: View, event: MotionEvent): Long {
        var recorder = active
        if (recorder == null) {
            val p = pending ?: return 0L
            if (!p.ready || event.actionMasked != MotionEvent.ACTION_DOWN || !matchesActiveInput(view, p.transport)) return 0L
            recorder = p.recorder
            pending = null
            active = recorder
            recorder.begin(run?.app ?: return 0L)
        }
        if (!matchesActiveInput(view, recorder.transport)) return 0L
        val now = SystemClock.uptimeNanos()
        recorder.recordEvent(event, now)
        return now
    }

    fun afterPage(tokenNs: Long, event: MotionEvent) {
        if (tokenNs == 0L) return
        val recorder = active ?: return
        recorder.handler.add(SystemClock.uptimeNanos() - tokenNs)
        if ((event.actionMasked == MotionEvent.ACTION_UP || event.actionMasked == MotionEvent.ACTION_CANCEL) &&
            (recorder.finishRequested || SystemClock.uptimeNanos() - recorder.startedNanos >= TARGET_BLOCK_NS)) {
            finishAsync(recorder)
        }
    }

    private fun requestFinish(recorder: Recorder) {
        if (active !== recorder) return
        if (recorder.inGesture) recorder.finishRequested = true else finishAsync(recorder)
    }

    private fun finishAsync(recorder: Recorder) {
        if (active !== recorder) return
        main.post { finishBlock(recorder) }
    }

    private fun finishBlock(recorder: Recorder) {
        if (active !== recorder) return
        recorder.endedNanos = SystemClock.uptimeNanos()
        recorder.targetFinish?.let(main::removeCallbacks)
        recorder.hardFinish?.let(main::removeCallbacks)
        active = null
        val state = run ?: return
        val end = endSnapshot(state.app)
        val result = resultFrom(recorder, end)
        state.results += result
        val next = recorder.index + 1
        if (next >= state.order.size) complete(state)
        else {
            Toast.makeText(state.app, "Block ${recorder.index + 1}/${state.order.size} captured. Preparing the next hidden method…", Toast.LENGTH_SHORT).show()
            main.postDelayed({ if (run === state) scheduleBlock(next) }, BETWEEN_BLOCK_MS)
        }
    }

    private fun scheduleBlock(index: Int) {
        val state = run ?: return
        val transport = state.order[index]
        PageTouchDispatch.arm = PageTouchDispatch.Arm.UNBUFFERED_140
        RendererArena.transport = transport
        val window = BubbleService.active?.window
        if (window == null || window.mode != FloatingMode.CHAT) {
            cancel("Floating page disappeared; benchmark canceled.")
            return
        }
        pending = null
        window.setRendererTransportForArena(transport)
        val deadline = SystemClock.uptimeMillis() + READY_TIMEOUT_MS
        fun poll() {
            if (run !== state) return
            if (rendererReady(transport)) {
                val pendingBlock = PendingBlock(index, index / 2, transport, Recorder(index, index / 2, transport))
                pending = pendingBlock
                Toast.makeText(state.app, "Block ${index + 1}/${state.order.size}: method ready after the vibration. Repeat the same up/down scrolling workload.", Toast.LENGTH_SHORT).show()
                main.postDelayed({
                    if (run === state && pending === pendingBlock && rendererReady(transport)) {
                        pendingBlock.ready = true
                        BubbleService.active?.window?.transitionView?.performHapticFeedback(HapticFeedbackConstants.CLOCK_TICK)
                    } else if (run === state && pending === pendingBlock) poll()
                }, READY_SETTLE_MS)
            } else if (SystemClock.uptimeMillis() < deadline) main.postDelayed({ poll() }, 100L)
            else cancel("Renderer did not become stable/focused; benchmark canceled rather than recording a bad block.")
        }
        poll()
    }

    private fun rendererReady(transport: RendererArena.Transport): Boolean {
        val window = BubbleService.active?.window ?: return false
        val tab = Workspace.peek()?.selected ?: return false
        val session = tab.session ?: return false
        val host = window.pageHost ?: return false
        val input = session.textInput.view ?: return false
        if (window.mode != FloatingMode.CHAT || Workspace.peek()?.floatingVisible != true ||
            host.transport != transport || host.view.session !== session || !input.isAttachedToWindow ||
            !window.transitionView.hasWindowFocus() || !input.hasWindowFocus() || !input.isShown) return false
        val relay = relayStats()
        return when (transport) {
            RendererArena.Transport.DIRECT_GECKO_SURFACE -> input === host.view && input is LiveGeckoView && relay[0] == 0L && relay[1] == 0L && relay[4] == 0L && relay[5] == 0L
            RendererArena.Transport.RELAY_LATEST_BP -> input !== host.view && input is SurfaceView && relay[0] > 0L && relay[5] > 0L
        }
    }

    private fun matchesActiveInput(view: View, transport: RendererArena.Transport): Boolean {
        val window = BubbleService.active?.window ?: return false
        val session = Workspace.peek()?.selected?.session ?: return false
        val host = window.pageHost ?: return false
        if (host.transport != transport || session.textInput.view !== view || !view.isAttachedToWindow) return false
        return when (transport) {
            RendererArena.Transport.DIRECT_GECKO_SURFACE -> view === host.view && view is LiveGeckoView
            RendererArena.Transport.RELAY_LATEST_BP -> view !== host.view && view is SurfaceView
        }
    }

    private fun resultFrom(recorder: Recorder, end: EndSnapshot): BlockResult {
        val durationMs = (recorder.endedNanos - recorder.startedNanos).coerceAtLeast(1L) / 1_000_000.0
        val seconds = durationMs / 1000.0
        val start = recorder.start
        val processCpu = (end.processCpuMs - start.processCpuMs).coerceAtLeast(0L) / seconds
        val mainCpu = (end.mainCpuNs - start.mainCpuNs).coerceAtLeast(0L) / 1_000_000.0 / seconds
        val relaySubmitted = delta(end.relay, start.relay, 2)
        val relayReleased = delta(end.relay, start.relay, 3)
        val relayErrors = delta(end.relay, start.relay, 6)
        val energy = if (start.energyNwh >= 0 && end.energyNwh >= 0) end.energyNwh - start.energyNwh else Long.MIN_VALUE
        return BlockResult(
            recorder.index, recorder.pair, recorder.transport, durationMs,
            recorder.eventCount, recorder.moveCount, recorder.historyEvents, recorder.historySamples,
            recorder.eventAge.percentile(.50), recorder.eventAge.percentile(.95),
            recorder.handler.percentile(.50), recorder.handler.percentile(.95),
            recorder.sampleSpacing.percentile(.50), recorder.sampleSpacing.percentile(.95),
            recorder.uiFrames.percentile(.50), recorder.uiFrames.percentile(.95),
            recorder.inputToUiFrame.percentile(.50), recorder.inputToUiFrame.percentile(.95),
            if (recorder.uiFrameCount == 0L) Double.NaN else recorder.uiJankCount * 100.0 / recorder.uiFrameCount,
            processCpu, mainCpu, end.pssKb, end.heapUsedBytes / 1024L, end.gcCount, end.allocatedBytes / 1024L,
            energy, end.currentUa, end.thermal, end.headroom, end.refreshRate,
            end.rxBytes - start.rxBytes, end.txBytes - start.txBytes,
            relaySubmitted, relayReleased, relayErrors, recorder.forcedFinish
        )
    }

    private fun complete(state: RunState) {
        if (run !== state) return
        val decisions = decisions(state)
        val overall = overall(decisions)
        val text = humanReport(state, decisions, overall)
        val json = jsonReport(state, decisions, overall)
        val saved = saveReports(state.app, text, json)
        val summary = "$overall\n${decisions.joinToString("\n") { "${it.name}: ${it.verdict}" }}\n${if (saved.isBlank()) "Saved in app benchmark files." else "Saved: $saved"}"
        state.app.getSharedPreferences("renderer-benchmark", Context.MODE_PRIVATE).edit()
            .putString("latest-summary", summary).apply()
        run = null
        pending = null
        active = null
        PageTouchDispatch.arm = PageTouchDispatch.Arm.UNBUFFERED_140
        RendererArena.transport = RendererArena.Transport.DIRECT_GECKO_SURFACE
        BubbleService.active?.window?.setRendererTransportForArena(RendererArena.Transport.DIRECT_GECKO_SURFACE)
        Toast.makeText(state.app, "Renderer benchmark complete. Opening the report summary.", Toast.LENGTH_LONG).show()
        main.postDelayed({
            state.app.startActivity(Intent(state.app, RendererArenaActivity::class.java).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_SINGLE_TOP))
        }, 700L)
    }

    private fun decisions(state: RunState): List<MetricDecision> {
        val pairs = (0 until state.pairs).mapNotNull { pair ->
            val blocks = state.results.filter { it.pair == pair }
            val direct = blocks.firstOrNull { it.transport == RendererArena.Transport.DIRECT_GECKO_SURFACE }
            val relay = blocks.firstOrNull { it.transport == RendererArena.Transport.RELAY_LATEST_BP }
            if (direct != null && relay != null) direct to relay else null
        }
        fun metric(name: String, unit: String, threshold: (List<Double>) -> Double, value: (BlockResult) -> Double): MetricDecision {
            val diffs = pairs.mapNotNull { (d, r) ->
                val dv = value(d); val rv = value(r)
                if (dv.isFinite() && rv.isFinite()) dv - rv else null
            }
            if (diffs.isEmpty()) return MetricDecision(name, unit, Double.NaN, Double.NaN, Double.NaN, Double.NaN, "UNAVAILABLE")
            val center = median(diffs)
            val ci = bootstrapMedianCi(diffs, state.seed xor name.hashCode().toLong())
            val t = threshold(diffs)
            val verdict = when {
                ci.second < -t -> "DIRECT WIN"
                ci.first > t -> "RELAY WIN"
                ci.first >= -t && ci.second <= t -> "EQUIVALENT"
                else -> "INCONCLUSIVE"
            }
            return MetricDecision(name, unit, center, ci.first, ci.second, t, verdict)
        }
        val pooledCpu = pairs.flatMap { listOf(it.first.appCpuMsPerSec, it.second.appCpuMsPerSec) }.filter { it.isFinite() }
        val cpuThreshold = max(1.0, (pooledCpu.average().takeIf { it.isFinite() } ?: 0.0) * .03)
        return listOf(
            metric("Input event age p95", "ms", { .25 }) { it.eventAgeP95Ms },
            metric("Page handler time p95", "ms", { .10 }) { it.handlerP95Ms },
            metric("Bubble process CPU", "ms CPU / s", { cpuThreshold }) { it.appCpuMsPerSec },
            metric("Bubble main-thread CPU", "ms CPU / s", { max(.5, cpuThreshold / 2) }) { it.mainCpuMsPerSec },
            metric("App Choreographer frame p95", "ms", { .25 }) { it.uiFrameP95Ms },
            metric("Input to next app frame p95", "ms", { .25 }) { it.inputToUiFrameP95Ms },
            metric("App Choreographer jank", "%", { .50 }) { it.uiJankPct }
        )
    }

    private fun overall(decisions: List<MetricDecision>): String {
        val primary = decisions.take(4).filter { it.verdict != "UNAVAILABLE" }
        val direct = primary.count { it.verdict == "DIRECT WIN" }
        val relay = primary.count { it.verdict == "RELAY WIN" }
        val equivalent = primary.count { it.verdict == "EQUIVALENT" }
        return when {
            direct >= 2 && relay == 0 -> "Overall: DIRECT favored by measured app/input-overhead metrics"
            relay >= 2 && direct == 0 -> "Overall: RELAY favored by measured app/input-overhead metrics"
            primary.isNotEmpty() && equivalent == primary.size -> "Overall: equivalent within predefined practical bounds"
            else -> "Overall: mixed / inconclusive — no honest single winner from these software metrics"
        }
    }

    private fun humanReport(state: RunState, decisions: List<MetricDecision>, overall: String): String = buildString {
        appendLine("Bubble renderer benchmark")
        appendLine("Generated: ${java.util.Date()}")
        appendLine("Pairs: ${state.pairs}; blocks: ${state.results.size}; seed: ${state.seed}")
        appendLine("Input policy: UNBUFFERED_140 for BOTH renderer arms")
        appendLine("Renderer A/B: DIRECT GeckoView SurfaceView vs relay_latest_bp")
        appendLine()
        appendLine(overall)
        appendLine()
        appendLine("PAIRED DECISIONS (direct minus relay; lower is better)")
        decisions.forEach { d ->
            appendLine("${d.name}: ${fmt(d.medianDirectMinusRelay)} ${d.unit}; 95% bootstrap CI [${fmt(d.ciLow)}, ${fmt(d.ciHigh)}], practical bound ±${fmt(d.threshold)} => ${d.verdict}")
        }
        appendLine()
        appendLine("RAW BLOCKS")
        state.results.forEach { b ->
            appendLine("block=${b.index + 1} pair=${b.pair + 1} method=${methodLabel(b.transport)} duration=${fmt(b.durationMs)}ms events=${b.events} moves=${b.moves} history=${b.historyEvents}/${b.historySamples} eventAgeP95=${fmt(b.eventAgeP95Ms)}ms handlerP95=${fmt(b.handlerP95Ms)}ms sourceSpacingP95=${fmt(b.sourceSpacingP95Ms)}ms appFrameP95=${fmt(b.uiFrameP95Ms)}ms inputToAppFrameP95=${fmt(b.inputToUiFrameP95Ms)}ms appJank=${fmt(b.uiJankPct)}% cpu=${fmt(b.appCpuMsPerSec)}ms/s mainCpu=${fmt(b.mainCpuMsPerSec)}ms/s pss=${b.pssKb}KB heap=${b.heapUsedKb}KB energy=${if (b.energyNwh == Long.MIN_VALUE) "unsupported" else "${b.energyNwh}nWh"} current=${b.currentUa}uA thermal=${b.thermal} headroom=${fmt(b.thermalHeadroom.toDouble())} refresh=${fmt(b.refreshRate.toDouble())}Hz net=${b.rxBytes}/${b.txBytes} relaySubmit=${b.relaySubmitted} relayRelease=${b.relayReleased} relayErrors=${b.relayErrors}")
        }
        appendLine()
        appendLine("SCOPE / HONESTY")
        appendLine("- Event age measures MotionEvent timestamp -> Bubble handler receipt. Handler time ends after the existing Gecko/APZ Java entry returns.")
        appendLine("- App Choreographer metrics describe Bubble's UI scheduler, not Gecko/WebRender or SurfaceFlinger presentation FPS.")
        appendLine("- Input->next app frame is NOT touch-to-photon latency.")
        appendLine("- CPU/PSS/heap/GC are Bubble app-process measurements; Gecko/system compositor work may run in other processes.")
        appendLine("- Battery/thermal/network readings are device-wide/noisy and are context, not automatic winner metrics.")
        appendLine("- Actual contact-to-photon requires an external high-speed camera/photodiode. Perfetto/FrameTimeline is the preferred software follow-up for compositor/scheduler analysis.")
        appendLine("- Relay submission counters are route proof: direct should add no relay submissions; relay should add them during rendered work.")
    }

