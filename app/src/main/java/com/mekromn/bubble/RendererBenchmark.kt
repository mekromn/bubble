    private fun saveReports(context: Context, text: String, json: String): String {
        val stamp = java.text.SimpleDateFormat("yyyyMMdd-HHmmss", java.util.Locale.US).format(java.util.Date())
        val dir = File(context.getExternalFilesDir(null), "renderer-benchmarks").apply { mkdirs() }
        File(dir, "renderer-$stamp.txt").writeText(text)
        File(dir, "renderer-$stamp.json").writeText(json)
        return runCatching {
            val values = ContentValues().apply {
                put(MediaStore.MediaColumns.DISPLAY_NAME, "Bubble-renderer-benchmark-$stamp.txt")
                put(MediaStore.MediaColumns.MIME_TYPE, "text/plain")
                put(MediaStore.MediaColumns.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS + "/Bubble Benchmarks")
                put(MediaStore.MediaColumns.IS_PENDING, 1)
            }
            val resolver = context.contentResolver
            val uri = resolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, values) ?: return@runCatching ""
            resolver.openOutputStream(uri)?.bufferedWriter()?.use { it.write(text) }
            values.clear(); values.put(MediaStore.MediaColumns.IS_PENDING, 0); resolver.update(uri, values, null, null)
            "Downloads/Bubble Benchmarks/Bubble-renderer-benchmark-$stamp.txt"
        }.getOrDefault("")
    }

    private fun endSnapshot(context: Context): EndSnapshot {
        val runtime = Runtime.getRuntime()
        val pm = context.getSystemService(PowerManager::class.java)
        return EndSnapshot(
            Process.getElapsedCpuTime(), Debug.threadCpuTimeNanos(), energyCounter(context), currentNow(context),
            safeUidRx(), safeUidTx(), Debug.getPss(), runtime.totalMemory() - runtime.freeMemory(),
            runtimeStatLong("art.gc.gc-count"), runtimeStatLong("art.gc.bytes-allocated"),
            pm.currentThermalStatus, runCatching { pm.getThermalHeadroom(10) }.getOrDefault(Float.NaN),
            currentRefreshRate() ?: Float.NaN, relayStats()
        )
    }

    private fun currentRefreshRate(): Float? = BubbleService.active?.window?.transitionView?.display?.refreshRate
    private fun relayStats(): LongArray = runCatching { NativeAhbBridge.nativeDebugStats() }.getOrElse { LongArray(10) }
    private fun delta(end: LongArray, start: LongArray, index: Int): Long = (end.getOrElse(index) { 0L } - start.getOrElse(index) { 0L }).coerceAtLeast(0L)
    private fun safeUidRx(): Long = TrafficStats.getUidRxBytes(Process.myUid()).coerceAtLeast(0L)
    private fun safeUidTx(): Long = TrafficStats.getUidTxBytes(Process.myUid()).coerceAtLeast(0L)
    private fun runtimeStatLong(key: String): Long = runCatching { Debug.getRuntimeStat(key)?.toLongOrNull() ?: -1L }.getOrDefault(-1L)
    private fun energyCounter(context: Context): Long = runCatching {
        context.getSystemService(BatteryManager::class.java).getLongProperty(BatteryManager.BATTERY_PROPERTY_ENERGY_COUNTER)
    }.getOrDefault(-1L).let { if (it <= 0L) -1L else it }
    private fun currentNow(context: Context): Int = runCatching {
        context.getSystemService(BatteryManager::class.java).getIntProperty(BatteryManager.BATTERY_PROPERTY_CURRENT_NOW)
    }.getOrDefault(Int.MIN_VALUE)

