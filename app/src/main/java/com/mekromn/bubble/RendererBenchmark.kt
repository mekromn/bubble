    private class Recorder(
        val index: Int,
        val pair: Int,
        val transport: RendererArena.Transport
    ) {
        val eventAge = Histogram(125_000L)          // 0.125 ms bins
        val handler = Histogram(25_000L)            // 0.025 ms bins
        val sampleSpacing = Histogram(125_000L)     // source-sample spacing
        val uiFrames = Histogram(125_000L)          // Bubble Choreographer cadence
        val inputToUiFrame = Histogram(125_000L)    // NOT presentation latency
        var startedNanos = 0L
        var endedNanos = 0L
        var eventCount = 0L
        var downCount = 0L
        var moveCount = 0L
        var upCount = 0L
        var cancelCount = 0L
        var historyEvents = 0L
        var historySamples = 0L
        var inGesture = false
        var finishRequested = false
        var forcedFinish = false
        var lastSourceSampleNanos = 0L
        var lastFrameNanos = 0L
        var pendingInputNanos = 0L
        var uiFrameCount = 0L
        var uiJankCount = 0L
        var nominalFrameNs = 8_333_333L
        lateinit var start: StartSnapshot
        var targetFinish: Runnable? = null
        var hardFinish: Runnable? = null

        fun begin(app: Context) {
            startedNanos = SystemClock.uptimeNanos()
            nominalFrameNs = currentRefreshRate()?.takeIf { it > 1f }?.let { (1_000_000_000.0 / it).toLong() } ?: 8_333_333L
            start = StartSnapshot(
                Process.getElapsedCpuTime(),
                Debug.threadCpuTimeNanos(),
                energyCounter(app),
                safeUidRx(),
                safeUidTx(),
                relayStats()
            )
            targetFinish = Runnable { requestFinish(this) }.also { main.postDelayed(it, TARGET_BLOCK_NS / 1_000_000L) }
            hardFinish = Runnable {
                if (active === this) {
                    forcedFinish = true
                    if (inGesture) cancel("A gesture stayed active too long; benchmark canceled rather than switching renderers under your finger.")
                    else finishAsync(this)
                }
            }.also { main.postDelayed(it, HARD_BLOCK_NS / 1_000_000L) }
        }

        fun recordEvent(event: MotionEvent, receiptNs: Long) {
            eventCount++
            eventAge.add(receiptNs - event.eventTimeNanos)
            if (pendingInputNanos == 0L) pendingInputNanos = receiptNs
            val history = event.historySize
            if (history > 0) {
                historyEvents++
                historySamples += history.toLong()
                for (i in 0 until history) recordSourceSample(event.getHistoricalEventTimeNanos(i))
            }
            recordSourceSample(event.eventTimeNanos)
            when (event.actionMasked) {
                MotionEvent.ACTION_DOWN -> { downCount++; inGesture = true }
                MotionEvent.ACTION_MOVE -> moveCount++
                MotionEvent.ACTION_UP -> { upCount++; inGesture = false }
                MotionEvent.ACTION_CANCEL -> { cancelCount++; inGesture = false }
            }
        }

        private fun recordSourceSample(timeNs: Long) {
            if (lastSourceSampleNanos != 0L && timeNs > lastSourceSampleNanos) sampleSpacing.add(timeNs - lastSourceSampleNanos)
            if (timeNs > lastSourceSampleNanos) lastSourceSampleNanos = timeNs
        }

        fun onFrame(frameNs: Long) {
            if (lastFrameNanos != 0L && frameNs > lastFrameNanos) {
                val delta = frameNs - lastFrameNanos
                uiFrames.add(delta)
                uiFrameCount++
                if (delta > nominalFrameNs * 3 / 2) uiJankCount++
            }
            lastFrameNanos = frameNs
            val input = pendingInputNanos
            if (input != 0L && frameNs >= input) {
                inputToUiFrame.add(frameNs - input)
                pendingInputNanos = 0L
            }
        }
    }

