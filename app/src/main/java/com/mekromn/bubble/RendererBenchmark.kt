    private fun median(values: List<Double>): Double {
        if (values.isEmpty()) return Double.NaN
        val sorted = values.sorted()
        val mid = sorted.size / 2
        return if (sorted.size % 2 == 1) sorted[mid] else (sorted[mid - 1] + sorted[mid]) / 2.0
    }

    private fun bootstrapMedianCi(values: List<Double>, seed: Long): Pair<Double, Double> {
        if (values.size == 1) return values[0] to values[0]
        val random = Random(seed)
        val samples = DoubleArray(2000)
        val temp = DoubleArray(values.size)
        repeat(samples.size) { iteration ->
            for (i in temp.indices) temp[i] = values[random.nextInt(values.size)]
            temp.sort()
            val mid = temp.size / 2
            samples[iteration] = if (temp.size % 2 == 1) temp[mid] else (temp[mid - 1] + temp[mid]) / 2.0
        }
        samples.sort()
        return samples[(samples.size * .025).toInt().coerceIn(samples.indices)] to
            samples[(samples.size * .975).toInt().coerceIn(samples.indices)]
    }

    private fun fmt(value: Double): String = if (!value.isFinite()) "n/a" else String.format(java.util.Locale.US, "%.3f", value)
    private fun finiteOrNull(value: Double): Any = if (value.isFinite()) value else JSONObject.NULL

    private object BuildFingerprint {
        fun seed(): Long {
            var value = 0xcbf29ce484222325UL.toLong()
            for (c in android.os.Build.FINGERPRINT) value = (value xor c.code.toLong()) * 0x100000001b3L
            return value
        }
    }
